using System;
using System.Collections.Generic;
using System.IO;
using FullSerializer;
using UnityEngine;

namespace FieldGuide
{
    // One trader as the player sees it (spec §8.3): the records of one `group` in the data, i.e. the same name and the
    // same buying rules. Welhö's two counters and Passmore's two doors are one Buyer each; Brom's and Kalle Ketku stay
    // apart (different names). SlotAllowed/SlotForbidden are the rule of the trader's storage slots that Trade.CheckIfFull
    // applies (design.md §9.3): the Storage's own lists, plus the slots' default "Storage" and "Unstorable" unless the
    // trader destroys what it buys (Trade.StartTrade clears them then, SRC/Trade.cs:345-351).
    internal sealed class Buyer
    {
        internal string Name;
        internal string[] Allowed, Forbidden, SlotAllowed, SlotForbidden;
        internal float Sell, StolenFactor;
        internal Money.Currency Currency;
        internal bool BuysStolen, Certificate;
        internal int OwnerId;
        internal readonly HashSet<string> Scenes = new HashSet<string>(StringComparer.Ordinal);
    }

    // Loads the embedded Data/traders.json (generated by tools/gen_traders.py from the exported scenes). A load or
    // validation failure logs one error and leaves Ok false: the tooltip and item-panel groups are skipped, the pop-ups
    // keep working (spec §4).
    internal static class TraderData
    {
        private const string Resource = "FieldGuide.Data.traders.json";
        private const long Schema = 2;

        // SlotController.DefaultForbiddenCategories (SRC/SlotController.cs:29), read from a fresh instance so a game
        // update that changes the list is followed.
        private static string[] _slotDefaults;

        internal static string[] SlotDefaults
        {
            get
            {
                if (_slotDefaults != null) return _slotDefaults;
                try { _slotDefaults = new SlotController().DefaultForbiddenCategories.ToArray(); }
                catch (Exception e)
                {
                    Log.Exception("Traders: slot defaults", e);
                    _slotDefaults = new[] { "Storage", "Unstorable" };
                }
                return _slotDefaults;
            }
        }

        // The storage-slot rule of a trader: its Storage's lists, plus the slot defaults unless it destroys purchases.
        internal static string[] SlotForbidden(string[] storageForbidden, bool destroysPurchases)
        {
            if (destroysPurchases) return storageForbidden ?? new string[0];
            var d = SlotDefaults;
            var f = storageForbidden ?? new string[0];
            var all = new string[f.Length + d.Length];
            f.CopyTo(all, 0);
            d.CopyTo(all, f.Length);
            return all;
        }

        internal static bool Ok;
        internal static string GameVersion = "?";
        // Sorted by Sell descending, then Name ordinal.
        internal static readonly List<Buyer> Buyers = new List<Buyer>();
        internal static readonly Dictionary<string, Buyer> ByKey = new Dictionary<string, Buyer>(StringComparer.Ordinal);
        internal static readonly Dictionary<string, Buyer> BySharedId = new Dictionary<string, Buyer>(StringComparer.Ordinal);
        // Keys the data lists but excludes (D16): known, never shown, not reported as unmatched.
        internal static readonly HashSet<string> Excluded = new HashSet<string>(StringComparer.Ordinal);

        internal static void Load()
        {
            Ok = false;
            Buyers.Clear();
            ByKey.Clear();
            BySharedId.Clear();
            Excluded.Clear();
            try
            {
                string json;
                using (var s = typeof(TraderData).Assembly.GetManifestResourceStream(Resource))
                {
                    if (s == null) throw new InvalidDataException("embedded resource missing");
                    using (var r = new StreamReader(s)) json = r.ReadToEnd();
                }
                var res = fsJsonParser.Parse(json, out fsData root);
                if (res.Failed) throw new InvalidDataException(res.FormattedMessages);
                var top = root.AsDictionary;
                if (Long(top, "schema") != Schema) throw new InvalidDataException("schema is not " + Schema);
                GameVersion = Str(top, "game");
                var groups = new Dictionary<string, Buyer>(StringComparer.Ordinal);
                var keys = new HashSet<string>(StringComparer.Ordinal);
                foreach (var t in List(top, "traders"))
                {
                    var d = t.AsDictionary;
                    string key = Str(d, "key");
                    if (string.IsNullOrEmpty(key) || !keys.Add(key)) throw new InvalidDataException("bad or duplicate key " + key);
                    if (d.TryGetValue("exclude", out var ex) && !ex.IsNull)
                    {
                        Excluded.Add(key);
                        continue;
                    }
                    string group = Str(d, "group"), name = Str(d, "name"), scene = Str(d, "scene");
                    if (string.IsNullOrEmpty(group) || string.IsNullOrEmpty(name) || string.IsNullOrEmpty(scene))
                        throw new InvalidDataException("missing group, name or scene in " + key);
                    if (!groups.TryGetValue(group, out var b))
                    {
                        string cur = Str(d, "sellCurrency");
                        if (cur != "OC" && cur != "RM") throw new InvalidDataException("bad currency in " + key);
                        b = new Buyer
                        {
                            Name = name,
                            Allowed = Tokens(d, "allowed"), Forbidden = Tokens(d, "forbidden"),
                            SlotAllowed = Tokens(d, "storageAllowed"),
                            SlotForbidden = SlotForbidden(Tokens(d, "storageForbidden"), Bool(d, "destroyPurchased")),
                            Sell = Num(d, "sell"), StolenFactor = Num(d, "stolenFactor"),
                            Currency = cur == "RM" ? Money.Currency.RM : Money.Currency.OC,
                            BuysStolen = Bool(d, "buysStolen"),
                            Certificate = d.TryGetValue("certificate", out var cert) && !cert.IsNull,
                            OwnerId = (int)Long(d, "ownerId"),
                        };
                        groups[group] = b;
                        Buyers.Add(b);
                    }
                    b.Scenes.Add(scene);
                    ByKey[key] = b;
                    string shared = Str(d, "sharedId");
                    if (!string.IsNullOrEmpty(shared)) BySharedId[shared] = b;
                }
                if (Buyers.Count == 0) throw new InvalidDataException("no traders");
                Buyers.Sort((x, y) =>
                {
                    int c = y.Sell.CompareTo(x.Sell);
                    return c != 0 ? c : string.CompareOrdinal(x.Name, y.Name);
                });
                Ok = true;
                if (GameVersion != Application.version)
                    Log.Warn($"Traders: the trader data was built from game {GameVersion}, running on {Application.version}. " +
                        "Traders the update changed may be listed wrong until Field Guide is updated.");
            }
            catch (Exception e)
            {
                Buyers.Clear();
                ByKey.Clear();
                BySharedId.Clear();
                Log.Error($"Traders: the trader data failed to load; Bought by is off this session: {e}");
            }
        }

        private static List<fsData> List(Dictionary<string, fsData> d, string k)
        {
            if (!d.TryGetValue(k, out var v) || !v.IsList) throw new InvalidDataException($"'{k}' is not a list");
            return v.AsList;
        }

        private static string Str(Dictionary<string, fsData> d, string k) =>
            d.TryGetValue(k, out var v) && v.IsString ? v.AsString : "";

        private static bool Bool(Dictionary<string, fsData> d, string k)
        {
            if (!d.TryGetValue(k, out var v) || !v.IsBool) throw new InvalidDataException($"'{k}' is not a bool");
            return v.AsBool;
        }

        private static long Long(Dictionary<string, fsData> d, string k)
        {
            if (d.TryGetValue(k, out var v))
            {
                if (v.IsInt64) return v.AsInt64;
                if (v.IsDouble) return (long)v.AsDouble;
            }
            throw new InvalidDataException($"'{k}' is not a number");
        }

        private static float Num(Dictionary<string, fsData> d, string k)
        {
            if (d.TryGetValue(k, out var v))
            {
                if (v.IsDouble) return (float)v.AsDouble;
                if (v.IsInt64) return v.AsInt64;
            }
            throw new InvalidDataException($"'{k}' is not a number");
        }

        // Never null (spec §8.1); entries are kept verbatim and in order.
        private static string[] Tokens(Dictionary<string, fsData> d, string k)
        {
            var list = List(d, k);
            var a = new string[list.Count];
            for (int i = 0; i < a.Length; i++)
            {
                if (!list[i].IsString) throw new InvalidDataException($"'{k}' holds a non-string");
                a[i] = list[i].AsString;
            }
            return a;
        }
    }
}
